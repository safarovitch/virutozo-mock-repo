// D2-03: writes src/generated/response-schemas.ts, a map from "METHOD /path/{template}" to the Zod
// schema of the operation's success response, built from contracts/openapi.yaml after Orval runs.
// customFetch uses it to validate responses in dev and test (API-5).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = fileURLToPath(new URL('../', import.meta.url));
const spec = parse(readFileSync(new URL('../../../contracts/openapi.yaml', import.meta.url), 'utf8'));
const pascal = (s) => s[0].toUpperCase() + s.slice(1);

const imports = new Map(); // file → names
const entries = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op || typeof op !== 'object' || !op.operationId) continue;
    if (op['x-transport'] === 'websocket') continue; // not called over HTTP (D2-04)
    const tag = String(op.tags?.[0] ?? '').toLowerCase();
    const file = `./zod/${tag}/${tag}.zod`;
    const name = `${pascal(op.operationId)}Response`;
    const source = readFileSync(`${root}src/generated/zod/${tag}/${tag}.zod.ts`, 'utf8');
    if (!new RegExp(`export const ${name}\\b`).test(source)) continue; // e.g. 204 responses
    if (!imports.has(file)) imports.set(file, []);
    imports.get(file).push(name);
    entries.push(`  '${method.toUpperCase()} ${path}': ${name},`);
  }
}

const out = [
  '// Generated by scripts/response-schemas.mjs from contracts/openapi.yaml. Do not edit manually.',
  "import type { ZodType } from 'zod';",
  ...[...imports].map(([file, names]) => `import { ${names.join(', ')} } from '${file}';`),
  '',
  'export const responseSchemas: Record<string, ZodType> = {',
  ...entries,
  '};',
  '',
].join('\n');
const target = `${root}src/generated/response-schemas.ts`;
if (!existsSync(`${root}src/generated`)) throw new Error('Run orval first');
writeFileSync(target, out);
console.log(`response-schemas: ${entries.length} operations`);
